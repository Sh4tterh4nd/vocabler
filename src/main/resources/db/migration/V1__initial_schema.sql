CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(40) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    active_limit INT NOT NULL DEFAULT 75,
    graduation_score DOUBLE PRECISION NOT NULL DEFAULT 8,
    correct_gain DOUBLE PRECISION NOT NULL DEFAULT 1,
    incorrect_penalty DOUBLE PRECISION NOT NULL DEFAULT 2,
    daily_decay DOUBLE PRECISION NOT NULL DEFAULT 0.2
);
CREATE TABLE language_pair (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_language VARCHAR(60) NOT NULL,
    target_language VARCHAR(60) NOT NULL,
    UNIQUE (source_language, target_language)
);
CREATE TABLE vocabulary_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pair_id BIGINT NOT NULL REFERENCES language_pair(id),
    source_text VARCHAR(200) NOT NULL,
    target_text VARCHAR(200) NOT NULL,
    notes VARCHAR(1000) NOT NULL DEFAULT '',
    UNIQUE (pair_id, source_text, target_text)
);
CREATE TABLE vocabulary_package (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pair_id BIGINT NOT NULL REFERENCES language_pair(id),
    name VARCHAR(100) NOT NULL,
    UNIQUE (pair_id, name)
);
CREATE TABLE package_entry (
    package_id BIGINT NOT NULL REFERENCES vocabulary_package(id) ON DELETE CASCADE,
    entry_id BIGINT NOT NULL REFERENCES vocabulary_entry(id) ON DELETE CASCADE,
    PRIMARY KEY (package_id, entry_id)
);
CREATE TABLE learning_progress (
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    entry_id BIGINT NOT NULL REFERENCES vocabulary_entry(id) ON DELETE CASCADE,
    direction VARCHAR(7) NOT NULL CHECK (direction IN ('FORWARD', 'REVERSE')),
    score DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (score >= 0 AND score <= 10),
    score_at TIMESTAMP WITH TIME ZONE NOT NULL,
    due_at TIMESTAMP WITH TIME ZONE NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    mastery_recall BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (user_id, entry_id, direction)
);
CREATE INDEX progress_due ON learning_progress(user_id, direction, active, due_at);
CREATE TABLE review_ticket (
    id VARCHAR(36) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    entry_id BIGINT NOT NULL REFERENCES vocabulary_entry(id) ON DELETE CASCADE,
    direction VARCHAR(7) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE (user_id, entry_id, direction)
);
CREATE TABLE review_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    entry_id BIGINT NOT NULL REFERENCES vocabulary_entry(id) ON DELETE CASCADE,
    direction VARCHAR(7) NOT NULL,
    correct BOOLEAN NOT NULL,
    score_before DOUBLE PRECISION NOT NULL,
    score_after DOUBLE PRECISION NOT NULL,
    reviewed_at TIMESTAMP WITH TIME ZONE NOT NULL
);
